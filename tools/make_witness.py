#!/usr/bin/env python3
"""Publish a checkpoint of the log and a countersignature over it.

The three objects this writes are the whole point of the mechanism: the log, the runtime's own
signature over its head, and a second party's signature over exactly that head. Nothing here is
generated by hand — every file is the output of the runtime, and the witness runs as its own command
with its own key, which is what keeps it from being a runtime signing its own work twice.

The two tampered copies exist so the demonstration page can show the check failing on real input
rather than describing it: one log with the last receipts dropped, and one attempt by the runtime to
countersign itself.
"""
import json
import os
import pathlib
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
DEMO = REPO / "demo"
MINT = REPO / "target" / "release" / "mint"
LOG = DEMO / "gate-receipts.json"


def run(args, env=None):
    full = dict(os.environ)
    if env:
        full.update(env)
    p = subprocess.run([str(MINT)] + args, cwd=str(REPO), capture_output=True, text=True, env=full)
    return p.returncode, (p.stdout + p.stderr).strip()


def main():
    if not LOG.exists():
        print(f"  no log at {LOG} — nothing to checkpoint")
        return 1

    rc, out = run(["checkpoint", "--receipts", str(LOG), "--out", str(DEMO / "checkpoint.json")])
    print(out)
    if rc != 0:
        print("  the checkpoint could not be signed")
        return rc

    # The witness's ledger is what makes a later, shorter log visible. On a first run it does not
    # exist; the command creates it.
    ledger = DEMO / "witness-ledger.json"
    if not ledger.exists():
        ledger.write_text("[]")
    rc, out = run([
        "witness", "--checkpoint", str(DEMO / "checkpoint.json"),
        "--out", str(DEMO / "witness.json"), "--ledger", str(ledger),
    ])
    print(out)
    if rc != 0:
        print("  the witness refused to countersign")
        return rc

    # Case 1: the same log with its last two receipts removed. The chain inside it is still perfect,
    # which is the whole reason a checkpoint is needed.
    cases = DEMO / "witness-cases"
    cases.mkdir(exist_ok=True)
    doc = json.loads(LOG.read_text())
    short = dict(doc)
    short["receipts"] = doc["receipts"][:-2]
    short["count"] = len(short["receipts"])
    (cases / "truncated.json").write_text(json.dumps(short, indent=2))

    # Case 2: the runtime trying to countersign its own head. It must be refused, and the refusal has
    # to be the runtime's own code saying so, not a rule written in a document somewhere.
    rc, out = run(
        ["witness", "--checkpoint", str(DEMO / "checkpoint.json"),
         "--out", str(cases / "self-witness.json"), "--ledger", str(cases / "self-ledger.json")],
        env={"MINT_ENDORSER_KEY": os.environ.get("MINT_RECEIPT_KEY", "/root/.secrets/mint-receipt.key")},
    )
    (cases / "self-witness.txt").write_text(out + "\n")
    print(out)

    cp = json.loads((DEMO / "checkpoint.json").read_text())
    wit = json.loads((DEMO / "witness.json").read_text())
    print()
    print(f"  checkpoint: {cp['body']['head']['count']} receipts, head {cp['body']['head']['head_hash'][:16]}"
          f", signed by {cp['body']['runtime'][:12]}")
    print(f"  witness:    countersigned by {wit['body']['witness'][:12]}"
          f" (runtime is {wit['body']['runtime'][:12]})")
    print(f"  ledger:     {len(json.loads(ledger.read_text()))} sighting(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
